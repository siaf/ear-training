    second: '2nd inv',
    third: '3rd inv',
    // Progressions
    I_V_vi_IV: 'I — V — vi — IV',
    vi_IV_I_V: 'vi — IV — I — V',
    I_vi_IV_V: 'I — vi — IV — V',
    I_IV_V_I: 'I — IV — V — I',
    ii_V_I_major: 'ii — V — I',
    ii_V_i_minor: 'iiø — V — i (minor)',
    V_of_V: 'V/V (→V)',
