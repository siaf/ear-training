    modulation_to_V: 'Modulated up a 5th',
    modulation_to_vi: 'Modulated to relative minor',
    // Jazz extensions
    '9': '9',
    '11': '11',
    '13': '13',
    '7b9': '7♭9',
    '7s9': '7♯9',
    '7s11': '7♯11',
    '7b13': '7♭13',
    // Borrowed chords
    iv: '♭iv (borrowed)',
    bIII: '♭III (borrowed)',
    bVI: '♭VI (borrowed)',
    bVII: '♭VII (borrowed)',
